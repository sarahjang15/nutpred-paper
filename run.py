def _parse_csv_arg(value):
    if not value:
        return []
    return [x.strip() for x in str(value).split(",") if x.strip()]


# Ingredient feature-group name -> column-getter. A --ing-feature token may
# "+"-join multiple group names (e.g. "binary+score+umap_20") to request one
# combined feature set rather than separate nut8+<group> comparison sets --
# needed to reproduce the paper's headline nut8+binary+score+umap20 model.
GROUP_COL_GETTERS = {
    "binary": lambda df: [c for c in df.columns if c.startswith("binary_")],
    "score": lambda df: [c for c in df.columns if c.startswith("score_")],
    "umap_2": lambda df: [c for c in df.columns if c.startswith("umap_2_")],
    "umap_10": lambda df: [c for c in df.columns if c.startswith("umap_10_")],
    "umap_20": lambda df: [c for c in df.columns if c.startswith("umap_20_")],
}


def _resolve_feature_sets(
    df: pd.DataFrame,
    nut8_cols: list,
    no_umap: bool,
    ing_features_raw: str,
    extra_feature_groups_raw: str,
    cluster_feature_col: str,
    cluster_feature_type: str,
    aux_cols: list = None,
):
    tokens = _parse_csv_arg(ing_features_raw)
    if not tokens:
        tokens = ["binary", "score", "umap_10", "umap_20"]
    if len(tokens) == 1 and tokens[0].strip().lower() == "all":
        tokens = ["binary", "score", "umap_2", "umap_10", "umap_20"]

    extra_cols = []
    selected_groups = {x.lower() for x in _parse_csv_arg(extra_feature_groups_raw)}
    selected_groups.discard("none")
    if "fortifier" in selected_groups:
        fortifier_cols = [c for c in df.columns if "fortifier" in c.lower()]
        if not fortifier_cols:
            raise ValueError(
                "--extra-feature-groups fortifier requested but no column containing "
                "'fortifier' was found in the loaded data. This feature group expects "
                "precomputed fortification columns (e.g. from "
                "data/snack_input_fortification_group.csv merged on fdc_id) -- it is not "
                "generated by this repo's code. See README.md for details."
            )
        extra_cols.extend(fortifier_cols)
    if "cluster" in selected_groups:
        cluster_candidates = [cluster_feature_col] if cluster_feature_col else ["cluster", "cluster_id", "cluster_label"]
        cluster_col = next((c for c in cluster_candidates if c and c in df.columns), None)
        if cluster_col is None:
            raise ValueError(
                "--extra-feature-groups cluster requested but no cluster column was found "
                "(looked for --cluster-feature-col, else 'cluster'/'cluster_id'/'cluster_label'). "
                "This feature group expects a precomputed cluster-label column -- it is not "
                "generated by this repo's code. Pass --cluster-feature-col explicitly if your "
                "cluster column has a different name. See README.md for details."
            )
        else:
            series = df[cluster_col]
            dtype_mode = cluster_feature_type
            if dtype_mode == "auto":
                dtype_mode = "onehot" if not pd.api.types.is_numeric_dtype(series) else "label"
            if dtype_mode == "onehot":
                dummies = pd.get_dummies(series.astype(str), prefix=cluster_col, dtype=float)
                for c in dummies.columns:
                    df[c] = dummies[c].values
                extra_cols.extend(list(dummies.columns))
            else:
                enc_col = f"{cluster_col}_label_encoded"
                df[enc_col], _ = pd.factorize(series.astype(str), sort=True)
                extra_cols.append(enc_col)

    if aux_cols:
        found_aux = [c for c in aux_cols if c in df.columns]
        missing_aux = [c for c in aux_cols if c not in df.columns]
        if missing_aux:
            logger.warning("--aux-feature columns not found, skipping: %s", missing_aux)
        extra_cols.extend(found_aux)

    feature_sets = {"nut8": list(nut8_cols)}
    for token in tokens:
        parts = [p.strip().lower() for p in str(token).split("+") if p.strip()]
        if not parts:
            continue
        cols = []
        ok = True
        for p in parts:
            getter = GROUP_COL_GETTERS.get(p)
            if getter is None:
                logger.warning("Unknown ingredient feature group %r in --ing-feature token %r, skipping", p, token)
                ok = False
                break
            if p.startswith("umap") and no_umap:
                ok = False
                break
            group_cols = getter(df)
            if not group_cols:
                ok = False
                break
            cols.extend(group_cols)
        if not ok or not cols:
            continue
        key = "nut8+" + "+".join(parts)
        feature_sets[key] = list(nut8_cols) + list(dict.fromkeys(cols))

    if extra_cols:
        dedup_extra = list(dict.fromkeys(extra_cols))
        for key in list(feature_sets.keys()):
            feature_sets[key] = list(dict.fromkeys(feature_sets[key] + dedup_extra))

    logger.info("Selected ingredient feature groups: %s", tokens)
    logger.info("Selected extra feature groups: %s", sorted(selected_groups) if selected_groups else ["none"])
    logger.info("Resolved feature sets: %s", {k: len(v) for k, v in feature_sets.items()})
    return feature_sets, df

